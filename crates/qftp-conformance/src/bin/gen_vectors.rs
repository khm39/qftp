//! Regenerate the golden `test-vectors/*.json` from the Rust reference
//! implementation. Run from anywhere in the workspace:
//!
//! ```text
//! cargo run -p qftp-conformance --bin gen-vectors
//! ```
//!
//! CI runs this and fails if the working tree changes, which catches
//! any unintended wire-format change.

use qftp_common::protocol::{ErrorResponse, Response};
use qftp_conformance::{
    error_code_samples, hex_encode, request_samples, response_samples, Vector, VectorFile,
};
use serde::Serialize;
use std::path::{Path, PathBuf};

fn make_vector<T: Serialize>(name: &str, description: &str, msg: &T) -> Vector {
    let framed = qftp_common::transport::encode_framed_message(msg).expect("encode_framed_message");
    Vector {
        name: name.to_string(),
        description: description.to_string(),
        value: serde_json::to_value(msg).expect("serde_json::to_value"),
        payload_hex: hex_encode(&framed[4..]),
        wire_hex: hex_encode(&framed),
    }
}

fn vectors_dir() -> PathBuf {
    // CARGO_MANIFEST_DIR is crates/qftp-conformance; the vectors live
    // at the repo root so a second implementation finds them easily.
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../test-vectors")
}

fn write_file(dir: &Path, file: &str, vf: &VectorFile) {
    let path = dir.join(file);
    let json = serde_json::to_string_pretty(vf).expect("serialize VectorFile");
    std::fs::write(&path, format!("{json}\n")).expect("write vector file");
    println!("wrote {} ({} vectors)", path.display(), vf.vectors.len());
}

fn main() {
    let dir = vectors_dir();
    std::fs::create_dir_all(&dir).expect("create test-vectors dir");

    let note = "Generated by `cargo run -p qftp-conformance --bin gen-vectors`. \
                Do not edit by hand. wire_hex = 4-byte big-endian length prefix + payload; \
                see spec/wire-format.md for the normative byte layout.";

    let requests = VectorFile {
        protocol: "qftp/1".into(),
        kind: "Request".into(),
        note: note.into(),
        vectors: request_samples()
            .into_iter()
            .map(|(n, d, m)| make_vector(n, d, &m))
            .collect(),
    };
    write_file(&dir, "requests.json", &requests);

    let responses = VectorFile {
        protocol: "qftp/1".into(),
        kind: "Response".into(),
        note: note.into(),
        vectors: response_samples()
            .into_iter()
            .map(|(n, d, m)| make_vector(n, d, &m))
            .collect(),
    };
    write_file(&dir, "responses.json", &responses);

    let error_codes = VectorFile {
        protocol: "qftp/1".into(),
        kind: "Response".into(),
        note: "One Response::Err per ErrorCode with an empty message, so the on-wire \
               discriminant of every code is fixed and validated. wire_hex = 4-byte \
               big-endian length prefix + payload; see spec/wire-format.md for the \
               normative byte layout."
            .into(),
        vectors: error_code_samples()
            .into_iter()
            .map(|(n, code)| {
                make_vector(
                    &format!("err_{n}"),
                    &format!("Response::Err carrying ErrorCode::{n} (empty message)."),
                    &Response::Err(ErrorResponse::new(code, "")),
                )
            })
            .collect(),
    };
    write_file(&dir, "error-codes.json", &error_codes);
}
